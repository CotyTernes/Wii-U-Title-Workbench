"""
Title catalog: which games, updates and DLC exist, so the app can say what a
library is missing.

The catalog is a JSON file generated by build_catalog.py. Nothing here touches
the network; this only reads what it is given.

    {"schema": 1, "generated": "...", "source": "...",
     "titles": {"0005000010101D00": {"name": ..., "code": ..., "region": ...,
                                     "versions": [0, 16, 32]}}}

Recorded versions are a floor, not a guarantee — a version absent from the list
may still exist.
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass, field
from pathlib import Path

BASE_PREFIXES = {"00050000", "00050002"}
UPDATE_PREFIX = "0005000E"
DLC_PREFIX = "0005000C"


@dataclass
class CatalogEntry:
    title_id: str
    name: str = ""
    code: str = ""
    region: str = ""
    versions: list[int] = field(default_factory=list)

    @property
    def latest_version(self) -> int | None:
        return max(self.versions) if self.versions else None


@dataclass
class GroupExpectation:
    """What the catalog believes exists for one unique ID."""

    unique_id: str
    base: list[CatalogEntry] = field(default_factory=list)
    updates: list[CatalogEntry] = field(default_factory=list)
    dlc: list[CatalogEntry] = field(default_factory=list)

    @property
    def name(self) -> str:
        for entry in self.base + self.updates + self.dlc:
            if entry.name:
                return entry.name
        return ""

    @property
    def display_name(self) -> str:
        """
        A name for the group as a whole.

        The base game's name is the good one. When only an update or DLC row
        exists, its name usually ends in "Update" or "DLC", which reads oddly
        as a heading, so that suffix is trimmed.
        """
        for entry in self.base:
            if entry.name:
                return entry.name
        for entry in self.updates + self.dlc:
            if entry.name:
                return re.sub(r"\s+(update|dlc|add-?on content)$", "", entry.name,
                              flags=re.IGNORECASE)
        return ""

    @property
    def region(self) -> str:
        for entry in self.base + self.updates + self.dlc:
            if entry.region:
                return entry.region
        return ""


@dataclass
class GroupReport:
    """What a group is missing, judged against the catalog."""

    unique_id: str
    known: bool                 # the catalog has heard of this unique ID
    name: str = ""
    missing: list[str] = field(default_factory=list)
    notes: list[str] = field(default_factory=list)

    @property
    def summary(self) -> str:
        if not self.known:
            return "Not in catalog"
        if self.missing:
            return "Missing: " + "; ".join(self.missing)
        return "Complete"

    @property
    def is_complete(self) -> bool:
        return self.known and not self.missing


class Catalog:
    """A loaded title catalog. An empty one reports everything as unknown."""

    def __init__(self, data: dict | None = None, path: Path | None = None):
        data = data or {}
        self.path = path
        self.generated: str = data.get("generated", "")
        self.source: str = data.get("source", "")
        self.entries: dict[str, CatalogEntry] = {}
        self._groups: dict[str, GroupExpectation] = {}

        for title_id, raw in (data.get("titles") or {}).items():
            title_id = title_id.upper()
            entry = CatalogEntry(
                title_id=title_id,
                name=raw.get("name", ""),
                code=raw.get("code", ""),
                region=raw.get("region", ""),
                versions=sorted({int(v) for v in raw.get("versions", [])}),
            )
            self.entries[title_id] = entry
            self._index(entry)

    def _index(self, entry: CatalogEntry) -> None:
        unique_id = entry.title_id[8:]
        prefix = entry.title_id[:8]
        group = self._groups.setdefault(unique_id, GroupExpectation(unique_id))
        if prefix in BASE_PREFIXES:
            group.base.append(entry)
        elif prefix == UPDATE_PREFIX:
            group.updates.append(entry)
        elif prefix == DLC_PREFIX:
            group.dlc.append(entry)

    # -- loading ------------------------------------------------------------

    @classmethod
    def load(cls, path: Path) -> "Catalog":
        with open(path, "r", encoding="utf-8") as handle:
            data = json.load(handle)
        if data.get("schema") != 1:
            raise ValueError(
                f"Catalog schema {data.get('schema')!r} isn't supported by this build"
            )
        return cls(data, path=path)

    @classmethod
    def empty(cls) -> "Catalog":
        return cls()

    def __len__(self) -> int:
        return len(self.entries)

    # -- queries ------------------------------------------------------------

    def region_for(self, title_id: str) -> str:
        entry = self.entries.get(title_id.upper())
        return entry.region if entry else ""

    def name_for(self, title_id: str) -> str:
        entry = self.entries.get(title_id.upper())
        return entry.name if entry else ""

    def expectation(self, unique_id: str) -> GroupExpectation | None:
        return self._groups.get(unique_id.upper())

    def groups(self) -> list[GroupExpectation]:
        """Every group the catalog knows, ordered for display."""
        return sorted(
            self._groups.values(),
            key=lambda g: (g.display_name.casefold() or "zzz", g.unique_id),
        )

    def report(self, unique_id: str, present: list[tuple[str, int]]) -> GroupReport:
        """
        Compare a group against the catalog.

        present is a list of (title_id, version) for everything the user has
        in this group.
        """
        unique_id = unique_id.upper()
        expectation = self._groups.get(unique_id)
        if expectation is None:
            return GroupReport(unique_id=unique_id, known=False)

        report = GroupReport(
            unique_id=unique_id, known=True, name=expectation.name
        )

        have = {tid.upper(): ver for tid, ver in present}
        have_prefixes = {tid[:8] for tid in have}

        # Base game
        if expectation.base and not (have_prefixes & BASE_PREFIXES):
            report.missing.append("base game")

        # Update: absent entirely, or older than the newest known version
        if expectation.updates:
            newest_known = max(
                (e.latest_version for e in expectation.updates if e.versions),
                default=None,
            )
            held = [v for tid, v in have.items() if tid[:8] == UPDATE_PREFIX]
            if not held:
                if newest_known is not None:
                    report.missing.append(f"update (v{newest_known} known)")
                else:
                    report.missing.append("update")
            elif newest_known is not None and max(held) < newest_known:
                report.missing.append(
                    f"newer update (have v{max(held)}, v{newest_known} known)"
                )

        # DLC: count distinct DLC title IDs
        if expectation.dlc:
            held_dlc = {tid for tid in have if tid[:8] == DLC_PREFIX}
            wanted_dlc = {e.title_id for e in expectation.dlc}
            absent = wanted_dlc - held_dlc
            if absent:
                if len(wanted_dlc) == 1:
                    report.missing.append("DLC")
                else:
                    report.missing.append(
                        f"{len(absent)} of {len(wanted_dlc)} DLC titles"
                    )

        # Things the user has that the catalog doesn't list are worth a note
        # rather than a warning — the catalog is incomplete, not authoritative.
        listed = {e.title_id for e in expectation.base + expectation.updates + expectation.dlc}
        extra = set(have) - listed
        if extra:
            report.notes.append(
                f"{len(extra)} title(s) here aren't in the catalog: "
                + ", ".join(sorted(extra))
            )

        return report
